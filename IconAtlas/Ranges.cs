using System.Collections.Generic;
using System.Linq;

namespace IconAtlas;

internal sealed record IconRange(int Index, uint Start, uint End, string Description, string Group)
{
    public int Count => (int)(End - Start + 1);
    public bool Contains(uint id) => id >= Start && id <= End;
    public string Ids => Start == End ? $"{Start:D6}" : $"{Start:D6} – {End:D6}";
}

